CREATE TABLE stock_monitor_target (
  stock_monitor_target_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  for_trade_date TEXT NOT NULL,
  source_trade_date TEXT NOT NULL,
  stock_identity_key TEXT NOT NULL REFERENCES stock_identity(stock_identity_key),
  code TEXT NOT NULL,
  exchange TEXT NOT NULL CHECK (exchange IN ('SH', 'SZ', 'BJ')),
  name TEXT NOT NULL,
  monitor_type TEXT NOT NULL CHECK (monitor_type IN ('stock_buy_monitor', 'stock_sell_monitor', 'open_position', 'stock_hint_monitor', 'manual_watch')),
  lane TEXT NOT NULL CHECK (lane IN ('stock_trade', 'stock_alert')),
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'paused', 'disabled', 'expired')),
  direction_scope TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[],
  source TEXT NOT NULL,
  source_version TEXT NOT NULL,
  raw_json JSONB,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE(for_trade_date, stock_identity_key, lane, monitor_type, source_version),
  CHECK (for_trade_date ~ '^[0-9]{8}$'),
  CHECK (source_trade_date ~ '^[0-9]{8}$'),
  CHECK (stock_identity_key = 'stock:' || exchange || ':' || code),
  CHECK (code ~ '^[0-9]{6}$'),
  CHECK (code !~ '^88[0-9]{4}$'),
  CHECK (direction_scope <@ ARRAY['buy', 'sell']::TEXT[]),
  CHECK (
    (lane = 'stock_trade' AND direction_scope <@ ARRAY['buy', 'sell']::TEXT[])
    OR lane = 'stock_alert'
  ),
  CHECK (lane <> 'stock_trade' OR monitor_type IN ('stock_buy_monitor', 'stock_sell_monitor', 'open_position')),
  CHECK (monitor_type <> 'stock_buy_monitor' OR direction_scope <@ ARRAY['buy']::TEXT[]),
  CHECK (monitor_type NOT IN ('stock_sell_monitor', 'open_position') OR direction_scope <@ ARRAY['sell']::TEXT[])
);

