-- A-share monitor v3 condition layer schema draft.
-- Stage N2-A only: review before running in any PostgreSQL database.
-- Boundary: condition eligibility only; no downstream runtime or trading tables.
-- Date convention: for_trade_date is the next trading day served by conditions;
-- source_trade_date is the finalized ingestion date and must equal prev_trade_date.

BEGIN;

CREATE TABLE common_condition_run (
  run_id TEXT PRIMARY KEY,
  for_trade_date TEXT NOT NULL,
  source_trade_date TEXT NOT NULL,
  prev_trade_date TEXT NOT NULL,
  source_version TEXT NOT NULL,
  source_versions JSONB NOT NULL DEFAULT '{}'::JSONB,
  source_ready_check JSONB,
  input_ingest_batch_id TEXT REFERENCES common_ingest_batch(batch_id),
  mode TEXT NOT NULL DEFAULT 'dry_run' CHECK (mode IN ('dry_run', 'execute')),
  status TEXT NOT NULL DEFAULT 'planned' CHECK (status IN ('planned', 'running', 'passed', 'passed_active', 'failed', 'blocked', 'superseded', 'rolled_back')),
  p0_count INTEGER NOT NULL DEFAULT 0 CHECK (p0_count >= 0),
  p1_count INTEGER NOT NULL DEFAULT 0 CHECK (p1_count >= 0),
  p2_count INTEGER NOT NULL DEFAULT 0 CHECK (p2_count >= 0),
  generated_by TEXT NOT NULL DEFAULT 'condition_layer',
  started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  finished_at TIMESTAMPTZ,
  raw_json JSONB,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (for_trade_date ~ '^[0-9]{8}$'),
  CHECK (source_trade_date ~ '^[0-9]{8}$'),
  CHECK (prev_trade_date ~ '^[0-9]{8}$'),
  CHECK (source_trade_date = prev_trade_date),
  CHECK (finished_at IS NULL OR finished_at >= started_at),
  CHECK (mode <> 'execute' OR p0_count = 0 OR status = 'blocked')
);

CREATE INDEX idx_common_condition_run_for_trade_date
ON common_condition_run(for_trade_date, status);

CREATE INDEX idx_common_condition_run_source_version
ON common_condition_run(source_version);

CREATE INDEX idx_common_condition_run_source_trade_date
ON common_condition_run(source_trade_date);

CREATE UNIQUE INDEX ux_common_condition_run_one_passed_active
ON common_condition_run(source_trade_date, for_trade_date)
WHERE status = 'passed_active';

CREATE TABLE common_condition_quality_item (
  quality_item_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  run_id TEXT NOT NULL REFERENCES common_condition_run(run_id) ON DELETE CASCADE,
  for_trade_date TEXT NOT NULL,
  source_trade_date TEXT NOT NULL,
  data_domain TEXT NOT NULL CHECK (data_domain IN ('common', 'stock', 'index', 'board')),
  layer_scope TEXT NOT NULL CHECK (layer_scope IN ('monitor_target', 'condition_basis', 'condition_pool', 'minute_target_scope', 'condition_run')),
  table_name TEXT,
  gate_code TEXT NOT NULL,
  gate_name TEXT NOT NULL,
  severity TEXT NOT NULL CHECK (severity IN ('P0', 'P1', 'P2')),
  status TEXT NOT NULL CHECK (status IN ('passed', 'failed', 'warning', 'skipped')),
  expected_value TEXT,
  actual_value TEXT,
  identity_key TEXT,
  details JSONB,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (for_trade_date ~ '^[0-9]{8}$'),
  CHECK (source_trade_date ~ '^[0-9]{8}$')
);

