-- A-share monitor v3 trigger layer schema draft.
-- Stage N4-0 only: review before running in any PostgreSQL database.
-- Boundary: trigger context/state/match/event contract only; no market data
-- pull, no action/user/voice/sim objects, no true trading, and no worker state.
--
-- Depends on:
--   sql/002_condition_layer_schema.sql
--   sql/006_market_data_layer_schema.sql
--   sql/008_common_event_infra_schema.sql

BEGIN;

CREATE TABLE common_trigger_run (
  run_id TEXT PRIMARY KEY,
  source_condition_run_id TEXT NOT NULL REFERENCES common_condition_run(run_id),
  source_market_data_run_id TEXT REFERENCES common_market_data_run(run_id),
  for_trade_date TEXT NOT NULL,
  source_trade_date TEXT NOT NULL,
  prev_trade_date TEXT NOT NULL,
  layer_role TEXT NOT NULL DEFAULT 'N4_trigger' CHECK (layer_role = 'N4_trigger'),
  mode TEXT NOT NULL DEFAULT 'dry_run' CHECK (mode IN ('dry_run', 'preflight', 'execute')),
  status TEXT NOT NULL DEFAULT 'planned' CHECK (status IN ('planned', 'running', 'passed', 'failed', 'blocked', 'superseded', 'rolled_back')),
  p0_count INTEGER NOT NULL DEFAULT 0 CHECK (p0_count >= 0),
  p1_count INTEGER NOT NULL DEFAULT 0 CHECK (p1_count >= 0),
  p2_count INTEGER NOT NULL DEFAULT 0 CHECK (p2_count >= 0),
  source_condition_row_count INTEGER NOT NULL DEFAULT 0 CHECK (source_condition_row_count >= 0),
  context_snapshot_row_count INTEGER NOT NULL DEFAULT 0 CHECK (context_snapshot_row_count >= 0),
  trigger_state_row_count INTEGER NOT NULL DEFAULT 0 CHECK (trigger_state_row_count >= 0),
  trigger_match_row_count INTEGER NOT NULL DEFAULT 0 CHECK (trigger_match_row_count >= 0),
  trigger_event_outbox_count INTEGER NOT NULL DEFAULT 0 CHECK (trigger_event_outbox_count >= 0),
  generated_by TEXT NOT NULL DEFAULT 'trigger_layer',
  market_data_pulled BOOLEAN NOT NULL DEFAULT false,
  action_layer_touched BOOLEAN NOT NULL DEFAULT false,
  user_layer_touched BOOLEAN NOT NULL DEFAULT false,
  voice_touched BOOLEAN NOT NULL DEFAULT false,
  sim_touched BOOLEAN NOT NULL DEFAULT false,
  real_trade_touched BOOLEAN NOT NULL DEFAULT false,
  worker_started BOOLEAN NOT NULL DEFAULT false,
  raw_json JSONB,
  started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  finished_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (for_trade_date ~ '^[0-9]{8}$'),
  CHECK (source_trade_date ~ '^[0-9]{8}$'),
  CHECK (prev_trade_date ~ '^[0-9]{8}$'),
  CHECK (source_trade_date = prev_trade_date),
  CHECK (finished_at IS NULL OR finished_at >= started_at),
  CHECK (market_data_pulled = false),
  CHECK (action_layer_touched = false),
  CHECK (user_layer_touched = false),
  CHECK (voice_touched = false),
  CHECK (sim_touched = false),
  CHECK (real_trade_touched = false),
  CHECK (mode <> 'dry_run' OR context_snapshot_row_count = 0),
  CHECK (mode <> 'dry_run' OR trigger_state_row_count = 0),
  CHECK (mode <> 'dry_run' OR trigger_match_row_count = 0),
  CHECK (mode <> 'dry_run' OR trigger_event_outbox_count = 0)
);

