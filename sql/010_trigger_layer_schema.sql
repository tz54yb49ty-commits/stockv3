  last_matched_at TIMESTAMPTZ,
  cleared_at TIMESTAMPTZ,
  raw_json JSONB,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE(run_id, for_trade_date, asset_kind, identity_key, direction, signal_type, condition_key, trigger_period, trigger_bucket),
  CHECK (for_trade_date ~ '^[0-9]{8}$'),
  CHECK (identity_key LIKE asset_kind || ':%'),
  CHECK (condition_key !~ '^(BUY:|BUY_HINT)' OR direction = 'buy'),
  CHECK (condition_key !~ '^(SELL:|SELL_HINT)' OR direction = 'sell'),
  CHECK (signal_type NOT IN ('B_BUY_30M_VOL', 'B_BUY', 'BUY_HINT') OR direction = 'buy'),
  CHECK (signal_type NOT IN ('S_SELL_30M_SHRINK', 'S_SELL', 'SELL_HINT') OR direction = 'sell'),
