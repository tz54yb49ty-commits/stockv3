  condition_key TEXT NOT NULL,
  trigger_period TEXT NOT NULL CHECK (trigger_period IN ('Y', 'Q', 'M', 'W', 'D', '30m')),
  trigger_bucket TEXT NOT NULL,
  current_status TEXT NOT NULL DEFAULT 'inactive' CHECK (current_status IN ('inactive', 'pending_market_data', 'matched', 'cleared')),
  last_source_event_id TEXT,
