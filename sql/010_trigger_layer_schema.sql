  CHECK (signal_type NOT IN ('S_SELL_30M_SHRINK', 'S_SELL', 'SELL_HINT') OR direction = 'sell'),
  CHECK (condition_key <> 'BUY_HINT' OR signal_type = 'BUY_HINT'),
  CHECK (condition_key <> 'SELL_HINT' OR signal_type = 'SELL_HINT'),
  CHECK (source_event_id <> ''),
  CHECK (output_event_id <> ''),
  CHECK (dedup_key <> ''),
  CHECK (trigger_bucket <> '')
);

